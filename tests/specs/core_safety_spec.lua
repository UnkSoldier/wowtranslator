-- Reset de securite : un relachement manque ne laisse jamais la traduction active.
return function(T)
  for _, ev in ipairs({ "PLAYER_LEAVING_WORLD", "PLAYER_ENTERING_WORLD" }) do
    T.test(ev .. " pendant l'appui : desactive et restaure", function()
      local m = T.boot()
      local spy = T.spyModule(m, "Spy")
      m.KeyDown()
      m.FireEvent(ev, false, false)
      T.eq(m.WT.IsActive(), false)
      T.eq(spy.restores, 1)
    end)

    T.test(ev .. " hors appui : rien a restaurer", function()
      local m = T.boot()
      local spy = T.spyModule(m, "Spy")
      m.FireEvent(ev, false, false)
      T.eq(m.WT.IsActive(), false)
      T.eq(spy.restores, 0)
    end)
  end

  T.test("'up' tardif apres un ecran de chargement : pas de second Restore", function()
    local m = T.boot()
    local spy = T.spyModule(m, "Spy")
    m.KeyDown()
    m.LoadingScreen("Ironforge")
    T.eq(m.WT.IsActive(), false)
    T.eq(spy.restores, 1)
    m.KeyUp()
    T.eq(spy.restores, 1)
  end)

  T.test("nouvel appui apres un reset", function()
    local m = T.boot()
    local spy = T.spyModule(m, "Spy")
    m.KeyDown()
    m.FireEvent("PLAYER_LEAVING_WORLD")
    m.KeyDown()
    T.eq(m.WT.IsActive(), true)
    T.eq(spy.applies, 2)
    m.KeyUp()
    T.eq(spy.restores, 2)
  end)
end
