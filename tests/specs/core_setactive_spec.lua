-- WT.SetActive(bool) : seul point de bascule (touche, reset, filet), idempotent.
return function(T)
  T.test("SetActive est expose", function()
    local m = T.boot()
    T.eq(type(m.WT.SetActive), "function", "WoWTranslator.SetActive")
  end)

  T.test("SetActive(true/false) : Apply/Restore une fois, IsActive coherent", function()
    local m = T.boot()
    local spy = T.spyModule(m, "Spy")
    m.WT.SetActive(true)
    T.eq(m.WT.IsActive(), true)
    m.WT.SetActive(true)
    T.eq(spy.applies, 1, "idempotent")
    m.WT.SetActive(false)
    m.WT.SetActive(false)
    T.eq(m.WT.IsActive(), false)
    T.eq(spy.restores, 1, "idempotent")
  end)

  T.test("SetActive et le raccourci partagent le meme etat", function()
    local m = T.boot()
    local spy = T.spyModule(m, "Spy")
    m.KeyDown()
    m.WT.SetActive(true)
    T.eq(spy.applies, 1, "deja actif via la touche")
    m.WT.SetActive(false)
    T.eq(m.WT.IsActive(), false)
    m.KeyUp()
    T.eq(spy.restores, 1, "'up' apres SetActive(false) : rien")
  end)

  T.test("SetActive avec une valeur non booleenne : pas d'erreur, etat booleen", function()
    local m = T.boot()
    T.noError(function() m.WT.SetActive(nil) end)
    T.eq(m.WT.IsActive(), false)
    T.noError(function() m.WT.SetActive(1) end)
    T.eq(type(m.WT.IsActive()), "boolean")
    m.WT.SetActive(false)
  end)
end
