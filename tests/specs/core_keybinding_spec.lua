-- Touche maintenue : Bindings.xml (runOnUp) -> WoWTranslator_OnHoldKey(keystate).
-- Filet de securite (PLAN.md T2) : pendant l'appui SEULEMENT, sondage de la
-- touche liee (GetBindingKey) via IsKeyDown ; si elle n'est plus enfoncee -> Restore.
return function(T)
  T.test("IsActive est faux au demarrage", function()
    local m = T.boot()
    T.eq(m.WT.IsActive(), false)
  end)

  T.test("handler global WoWTranslator_OnHoldKey", function()
    local m = T.boot()
    T.eq(type(m.env.WoWTranslator_OnHoldKey), "function", "WoWTranslator_OnHoldKey doit etre GLOBALE")
  end)

  T.test("'down' active, 'up' desactive", function()
    local m = T.boot()
    m.KeyDown()
    T.eq(m.WT.IsActive(), true, "apres down")
    m.KeyUp()
    T.eq(m.WT.IsActive(), false, "apres up")
  end)

  T.test("repetition de 'down' (auto-repeat) idempotente", function()
    local m = T.boot()
    local spy = T.spyModule(m, "Spy")
    for _ = 1, 5 do m.KeyDown() end
    T.eq(m.WT.IsActive(), true)
    T.eq(spy.applies, 1, "Apply une seule fois malgre 5 'down'")
    m.KeyUp()
    T.eq(spy.restores, 1)
  end)

  T.test("'up' sans 'down' : sans erreur, sans Restore", function()
    local m = T.boot()
    local spy = T.spyModule(m, "Spy")
    m.KeyUp()
    m.KeyUp()
    T.eq(m.WT.IsActive(), false)
    T.eq(spy.restores, 0, "Restore seulement lors du passage actif -> inactif")
  end)

  T.test("cycles successifs", function()
    local m = T.boot()
    local spy = T.spyModule(m, "Spy")
    for _ = 1, 3 do m.KeyDown(); m.KeyUp() end
    T.eq(spy.applies, 3)
    T.eq(spy.restores, 3)
    T.eq(m.WT.IsActive(), false)
  end)

  T.test("valeur de keystate inattendue : pas d'erreur", function()
    local m = T.boot()
    T.noError(function() m.env.WoWTranslator_OnHoldKey(nil) end)
    T.noError(function() m.env.WoWTranslator_OnHoldKey("bogus") end)
    T.eq(type(m.WT.IsActive()), "boolean")
  end)

  T.test("fonctionne en combat (pas de dependance a InCombatLockdown)", function()
    local m = T.boot()
    m.inCombat = true
    m.KeyDown()
    T.eq(m.WT.IsActive(), true)
    m.KeyUp()
    T.eq(m.WT.IsActive(), false)
  end)

  -- Filet de securite ----------------------------------------------------

  T.test("filet IsKeyDown : ne coupe pas tant que la touche est tenue", function()
    local m = T.boot()
    m.KeyDown()
    m.Wait(3)
    T.eq(m.WT.IsActive(), true, "touche toujours enfoncee")
    m.KeyUp()
    T.eq(m.WT.IsActive(), false)
  end)

  T.test("filet IsKeyDown : 'up' perdu (perte de focus) -> Restore en moins d'une seconde", function()
    local m = T.boot()
    local spy = T.spyModule(m, "Spy")
    m.KeyDown()
    m.Wait(0.3)
    m.LoseKeyUp()
    m.Wait(1)
    T.eq(m.WT.IsActive(), false, "le filet doit desactiver quand la touche n'est plus enfoncee")
    T.eq(spy.restores, 1)
    m.KeyUp() -- 'up' tardif eventuel
    T.eq(spy.restores, 1, "pas de second Restore")
  end)

  T.test("filet IsKeyDown : aucun sondage hors appui", function()
    local m = T.boot()
    m.Wait(2)
    T.eq(m.isKeyDownCalls, 0, "IsKeyDown appele alors que la touche n'est pas tenue")
    m.KeyDown(); m.Wait(0.5); m.KeyUp()
    local after = m.isKeyDownCalls
    m.Wait(2)
    T.eq(m.isKeyDownCalls, after, "le sondage doit s'arreter apres le relachement")
  end)

  T.test("filet IsKeyDown : touche avec modificateur (SHIFT-F6) -> sonde la touche de base", function()
    local m = T.boot({ boundKey = "SHIFT-F6" })
    m.KeyDown()
    m.Wait(2)
    T.eq(m.WT.IsActive(), true, "IsKeyDown(\"SHIFT-F6\") non confirme : retirer le modificateur et sonder \"F6\"")
    m.LoseKeyUp()
    m.Wait(1)
    T.eq(m.WT.IsActive(), false)
  end)

  T.test("filet : deux touches liees, la SECONDE tenue -> pas de coupure", function()
    local m = T.boot({ boundKeys = { "F6", "BUTTON4" } })
    m.KeyDown(2)
    m.Wait(2)
    T.eq(m.WT.IsActive(), true, "GetBindingKey renvoie deux touches : sonder les deux")
    m.LoseKeyUp(2)
    m.Wait(1)
    T.eq(m.WT.IsActive(), false, "aucune touche tenue -> desactive")
  end)

  T.test("filet : deux touches liees, la premiere tenue -> pas de coupure", function()
    local m = T.boot({ boundKeys = { "F6", "BUTTON4" } })
    m.KeyDown(1)
    m.Wait(2)
    T.eq(m.WT.IsActive(), true)
    m.KeyUp(1)
    T.eq(m.WT.IsActive(), false)
  end)

  T.test("filet : touche liee a '-' avec modificateur (SHIFT--) -> touche de base '-'", function()
    local m = T.boot({ boundKey = "SHIFT--" })
    m.KeyDown()
    m.Wait(2)
    T.eq(m.WT.IsActive(), true, "SHIFT-- -> '-' (ne pas couper sur le dernier tiret)")
    m.LoseKeyUp()
    m.Wait(1)
    T.eq(m.WT.IsActive(), false)
  end)

  T.test("filet : IsKeyDown renvoie nil (inconnu) -> jamais de coupure", function()
    local m = T.boot({ isKeyDownUnknown = true })
    m.KeyDown()
    m.LoseKeyUp()
    m.Wait(2)
    T.eq(m.WT.IsActive(), true, "nil = inconnu : ne pas couper")
    m.KeyUp()
    T.eq(m.WT.IsActive(), false)
  end)

  T.test("filet : une touche false + une touche nil (inconnue) -> reste actif", function()
    -- PLAN.md T2 : coupe seulement si TOUTES renvoient exactement false.
    local m = T.boot({ boundKeys = { "F6", "BUTTON4" }, unknownKeys = { BUTTON4 = true } })
    m.KeyDown(1)
    m.LoseKeyUp(1)
    m.Wait(2)
    T.eq(m.WT.IsActive(), true, "nil = inconnu : ne pas couper")
    m.KeyUp(1)
    T.eq(m.WT.IsActive(), false)
  end)

  T.test("filet arme UNIQUEMENT par la touche : SetActive(true) seul n'est pas coupe", function()
    -- PLAN.md T2 : WoWTranslator_OnHoldKey("down") arme le filet ; un
    -- WT.SetActive(true) venant d'ailleurs ne l'arme pas.
    local m = T.boot()
    m.WT.SetActive(true) -- aucune touche tenue
    m.Wait(2)
    T.eq(m.WT.IsActive(), true, "SetActive(true) programmatique : le filet ne doit pas couper")
    m.WT.SetActive(false)
    T.eq(m.WT.IsActive(), false)
  end)

  T.test("filet arme par CHAQUE 'down', meme si deja actif (SetActive(true) puis touche)", function()
    -- PLAN.md T2 : tout WoWTranslator_OnHoldKey("down") arme le filet.
    local m = T.boot()
    m.WT.SetActive(true) -- activation programmatique : filet non arme
    m.KeyDown()          -- la touche arrive ensuite : le filet doit s'armer
    m.LoseKeyUp()
    m.Wait(1)
    T.eq(m.WT.IsActive(), false, "le 'down' sur un etat deja actif doit armer le filet")
  end)

  T.test("filet desarme a la desactivation, rearme au prochain appui", function()
    local m = T.boot()
    m.KeyDown(); m.KeyUp()
    m.WT.SetActive(true)
    m.Wait(2)
    T.eq(m.WT.IsActive(), true, "le filet de l'appui precedent ne doit plus agir")
    m.WT.SetActive(false)
    m.KeyDown()
    m.LoseKeyUp()
    m.Wait(1)
    T.eq(m.WT.IsActive(), false, "nouvel appui : filet rearme")
  end)

  T.test("sans IsKeyDown : fonctionne, pas d'erreur, pas de coupure", function()
    local m = T.boot({ noIsKeyDown = true })
    m.KeyDown()
    m.Wait(2)
    T.eq(m.WT.IsActive(), true, "rester actif tant que 'up' n'est pas recu")
    m.KeyUp()
    T.eq(m.WT.IsActive(), false)
  end)

  T.test("aucune touche liee (GetBindingKey nil) : pas d'erreur, jamais de coupure", function()
    local m = T.boot({ noBoundKey = true })
    m.env.WoWTranslator_OnHoldKey("down")
    m.Wait(2)
    T.eq(m.WT.IsActive(), true, "sans touche liee, le filet ne coupe pas")
    m.env.WoWTranslator_OnHoldKey("up")
    T.eq(m.WT.IsActive(), false)
  end)
end
