-- Registre de modules : Apply a l'activation, Restore au relachement.
return function(T)
  T.test("Apply a l'activation, Restore au relachement, une fois chacun", function()
    local m = T.boot()
    local spy = T.spyModule(m, "Spy")
    T.eq(spy.applies, 0, "pas d'Apply a l'enregistrement")
    m.KeyDown()
    T.eq(spy.applies, 1)
    T.eq(spy.restores, 0)
    m.KeyUp()
    T.eq(spy.applies, 1)
    T.eq(spy.restores, 1)
  end)

  T.test("plusieurs modules : tous appeles", function()
    local m = T.boot()
    local a = T.spyModule(m, "SpyA")
    local b = T.spyModule(m, "SpyB")
    m.KeyDown()
    m.KeyUp()
    T.eq(a.applies, 1); T.eq(b.applies, 1)
    T.eq(a.restores, 1); T.eq(b.restores, 1)
  end)

  T.test("IsActive() vrai pendant Apply, faux pendant Restore", function()
    -- Indispensable aux hooks : pendant Restore, le module remet le texte
    -- d'origine via SetText ; si IsActive() etait encore vrai, son propre
    -- hook retraduirait aussitot.
    local m = T.boot()
    local spy = T.spyModule(m, "Spy")
    m.KeyDown()
    m.KeyUp()
    T.eq(spy.activeInApply[1], true, "IsActive() pendant Apply")
    T.eq(spy.activeInRestore[1], false, "IsActive() pendant Restore")
  end)

  T.test("un Apply en erreur n'empeche pas les autres modules", function()
    local m = T.boot()
    local bad = T.spyModule(m, "Bad", { applyError = "boom-apply" })
    local good = T.spyModule(m, "Good")
    m.KeyDown()
    T.eq(good.applies, 1, "le module sain est applique")
    T.eq(m.WT.IsActive(), true, "l'etat reste actif")
    local errs = T.takeErrors(m)
    T.ok(#errs >= 1 and errs[1]:find("boom-apply", 1, true),
      "l'erreur doit etre signalee via geterrorhandler() (visible avec scriptErrors 1), pas avalee")
    m.KeyUp()
    T.eq(bad.restores, 1, "Restore appele aussi pour le module en echec (annule un Apply partiel)")
    T.eq(good.restores, 1)
  end)

  T.test("un Restore en erreur n'empeche ni les autres Restore ni la desactivation", function()
    local m = T.boot()
    local bad = T.spyModule(m, "Bad", { restoreError = "boom-restore" })
    local good = T.spyModule(m, "Good")
    m.KeyDown()
    m.KeyUp()
    T.eq(good.restores, 1)
    T.eq(m.WT.IsActive(), false, "jamais bloque en mode traduit")
    local errs = T.takeErrors(m)
    T.ok(#errs >= 1 and errs[1]:find("boom-restore", 1, true), "erreur signalee")
    m.KeyDown()
    T.eq(good.applies, 2, "nouvel appui possible")
    T.eq(bad.applies, 2)
    m.KeyUp()
    T.takeErrors(m)
  end)

  T.test("les erreurs d'un module ne remontent pas jusqu'au binding", function()
    local m = T.boot()
    T.spyModule(m, "Bad", { applyError = "x", restoreError = "y" })
    T.noError(function() m.env.WoWTranslator_OnHoldKey("down") end)
    T.noError(function() m.env.WoWTranslator_OnHoldKey("up") end)
    T.takeErrors(m)
  end)
end
